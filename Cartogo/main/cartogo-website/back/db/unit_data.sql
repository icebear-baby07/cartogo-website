create table if not exists public.unit_data (
  id bigint generated by default as identity primary key,
  brand text not null,
  model text not null,
  display_name text not null,
  capacity integer not null check (capacity > 0),
  in12_rate numeric(10, 2) not null default 0 check (in12_rate >= 0),
  in24_rate numeric(10, 2) not null default 0 check (in24_rate >= 0),
  out12_rate numeric(10, 2) not null default 0 check (out12_rate >= 0),
  out24_rate numeric(10, 2) not null default 0 check (out24_rate >= 0),
  luzon_rate numeric(10, 2) not null default 0 check (luzon_rate >= 0),
  status text not null default 'Available'
    check (status in ('Available', 'Rented', 'Maintenance', 'Inactive')),
  features text[] not null default '{}'
);

alter table public.unit_data
  add column if not exists in12_rate numeric(10, 2) not null default 0 check (in12_rate >= 0),
  add column if not exists in24_rate numeric(10, 2) not null default 0 check (in24_rate >= 0),
  add column if not exists out12_rate numeric(10, 2) not null default 0 check (out12_rate >= 0),
  add column if not exists out24_rate numeric(10, 2) not null default 0 check (out24_rate >= 0),
  add column if not exists luzon_rate numeric(10, 2) not null default 0 check (luzon_rate >= 0);

do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'unit_data' and column_name = 'daily_rate'
  ) then
    update public.unit_data set in24_rate = daily_rate;
  end if;
end;
$$;

alter table public.unit_data drop column if exists daily_rate;

alter table public.unit_data enable row level security;

drop policy if exists unit_data_public_read on public.unit_data;
create policy unit_data_public_read
  on public.unit_data for select
  to anon, authenticated
  using (status <> 'Inactive' or public.is_cartogo_admin());

revoke all on public.unit_data from public, anon, authenticated;
grant select on public.unit_data to anon, authenticated;
grant all on public.unit_data to service_role;
grant execute on function public.is_cartogo_admin() to anon;

do $$
declare
  unit_data_sequence text := pg_get_serial_sequence('public.unit_data', 'id');
begin
  if unit_data_sequence is not null then
    execute format('grant usage, select on sequence %s to service_role', unit_data_sequence);
  end if;
end;
$$;