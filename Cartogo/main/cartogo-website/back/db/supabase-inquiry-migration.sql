  on public.inquiries for select to authenticated
  using (public.is_cartogo_admin());
create policy cartogo_inquiries_admin_update
  on public.inquiries for update to authenticated
  using (public.is_cartogo_admin())
  with check (public.is_cartogo_admin());
create policy cartogo_inquiries_admin_delete
  on public.inquiries for delete to authenticated
  using (public.is_cartogo_admin());
create policy cartogo_inquiries_verified_insert
  on public.inquiries for insert to authenticated
  with check (
    (
      verification_method = 'phone_otp'
      and user_id is null
      and status = 'pending_review'
      and phone = auth.jwt() ->> 'phone'
    )
    or
    (
      verification_method = 'google_oauth'
      and user_id = auth.uid()
      and status = 'confirmed'
      and lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
      and auth.jwt() -> 'app_metadata' ->> 'provider' = 'google'
      and auth.jwt() -> 'user_metadata' ->> 'email_verified' = 'true'
    )
  );
