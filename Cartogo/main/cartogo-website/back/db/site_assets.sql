create table if not exists public.site_assets (
  id bigint generated by default as identity primary key,
  asset_type text not null default 'location'
    check (asset_type in ('location', 'contact')),
  loc_name text,
  coordinates jsonb,
  display_name text not null,
  description text not null default '',
  opening_hours time,
  closing_hours time,
  status text not null default 'open'
    check (status in ('open', 'closed')),
  phone text,
  email text,
  operational_hours text,
  constraint site_assets_location_fields_check check (
    asset_type = 'contact'
    or (
      loc_name is not null
      and coordinates is not null
      and jsonb_typeof(coordinates) = 'object'
      and coordinates ? 'lat'
      and coordinates ? 'lng'
      and (coordinates ->> 'lat') ~ '^-?[0-9]+([.][0-9]+)?$'
      and (coordinates ->> 'lng') ~ '^-?[0-9]+([.][0-9]+)?$'
    )
  )
);

create unique index if not exists site_assets_location_name_unique
  on public.site_assets (loc_name)
  where asset_type = 'location';

create unique index if not exists site_assets_contact_unique
  on public.site_assets (asset_type)
  where asset_type = 'contact';

alter table public.site_assets enable row level security;

drop policy if exists site_assets_public_read on public.site_assets;
create policy site_assets_public_read
  on public.site_assets for select
  using (true);

revoke all on public.site_assets from public, anon, authenticated;
grant select on public.site_assets to anon, authenticated;

